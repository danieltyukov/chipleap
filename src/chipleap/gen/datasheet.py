"""Register map (reggen hjson) and a Markdown datasheet for a generated design.

The register description uses the hjson format of OpenTitan's reggen, which X-HEEP uses
for its own peripherals, so the accelerator's registers can be fed to the same tools.
The datasheet is the specification document of the design point: memory map, register
map, interfaces, programming sequence and the model's predictions.
"""

from __future__ import annotations

from dataclasses import dataclass

from chipleap.gen.rtl import DEFAULT_REG_BASE, rtl_params
from chipleap.gen.xheep import code_section_bytes, ext_window
from chipleap.hw.design import DATAFLOW_NAMES, Design
from chipleap.hw.memory import get_memory
from chipleap.hw.tech import get_tech
from chipleap.model.accel import ACC_ROWS


@dataclass(frozen=True)
class Reg:
    name: str
    offset: int
    access: str  # rw, ro, wo
    desc: str
    fields: tuple[tuple[str, str, str], ...] = ()  # (bits, name, description)


REGISTERS: tuple[Reg, ...] = (
    Reg(
        "CTRL",
        0x00,
        "wo",
        "Control.",
        (("0", "START", "Write 1 to start a job. Ignored while busy."),),
    ),
    Reg(
        "STATUS",
        0x04,
        "ro",
        "Status.",
        (
            ("0", "BUSY", "A job is running."),
            ("1", "DONE", "The last job finished. Cleared by START."),
        ),
    ),
    Reg("X_ADDR", 0x08, "rw", "Byte address of X, M x K int8, row-major."),
    Reg("W_ADDR", 0x0C, "rw", "Byte address of W, N x K packed weights, row-major."),
    Reg("Y_ADDR", 0x10, "rw", "Byte address of Y, M x N int32, row-major."),
    Reg("M", 0x14, "rw", "Rows of X and Y."),
    Reg("K", 0x18, "rw", "Reduction length, padded to the K alignment (see chipleap_plan)."),
    Reg("N", 0x1C, "rw", "Rows of W, columns of Y."),
    Reg("TM", 0x20, "rw", "Tile rows of X (from chipleap_plan)."),
    Reg("TK", 0x24, "rw", "Tile depth along K (from chipleap_plan)."),
    Reg("FMT", 0x28, "rw", "Weight format in bits: 8, 4 or 2."),
    Reg(
        "XRES",
        0x2C,
        "rw",
        "Activation block resident.",
        (("0", "XRES", "Set from chipleap_plan."),),
    ),
    Reg("CYCLES", 0x30, "ro", "Cycles taken by the last job."),
    Reg(
        "INFO",
        0x34,
        "ro",
        "Build parameters.",
        (
            ("31:24", "ROWS", "Array rows."),
            ("23:16", "COLS", "Array columns."),
            ("15:12", "WBITS", "Widest weight format."),
            ("11:4", "PORTS", "Read ports."),
            ("1:0", "DATAFLOW", "0 gemv, 1 weight stationary, 2 output stationary."),
        ),
    ),
    Reg(
        "IRQ_EN", 0x38, "rw", "Interrupt enable.", (("0", "EN", "Raise irq_o while DONE is set."),)
    ),
)


def reggen_hjson(name: str) -> str:
    regs = []
    for r in REGISTERS:
        fields = r.fields or (("31:0", r.name, r.desc),)
        fl = ",\n".join(
            f'        {{ bits: "{b}", name: "{n}", desc: "{d}" }}' for b, n, d in fields
        )
        regs.append(
            f'    {{ name: "{r.name}",\n      desc: "{r.desc}",\n      swaccess: "{r.access}",\n'
            f'      hwaccess: "hro",\n      fields: [\n{fl}\n      ]\n    }}'
        )
    return (
        "// Register description of the ChipLeap accelerator, in OpenTitan reggen hjson.\n"
        f'// Generated for design "{name}". SPDX-License-Identifier: MIT\n'
        "{\n"
        '  name: "chipleap_accel",\n'
        '  clocking: [{ clock: "clk_i", reset: "rst_ni" }],\n'
        '  bus_interfaces: [{ protocol: "reg_iface", direction: "device" }],\n'
        '  regwidth: "32",\n'
        "  registers: [\n" + ",\n".join(regs) + "\n  ]\n}\n"
    )


def _clock(d: Design) -> str:
    """The SoC's clock: the design's, or what X-HEEP's SoC meets where that is less."""
    from chipleap.model.evaluate import soc_limit_mhz

    limit = soc_limit_mhz(d, get_tech(d.tech))
    if limit is None or limit >= d.freq_mhz:
        return f"{d.freq_mhz:g} MHz"
    return (
        f"{limit:.1f} MHz, what X-HEEP's SoC meets on {d.tech} (the accelerator is built for "
        f"{d.freq_mhz:g} MHz)"
    )


def datasheet(
    d: Design,
    *,
    spec_name: str = "",
    ext_bytes: float = 0.0,
    metrics: dict[str, float] | None = None,
    unit: str = "token",
    workload: str = "",
) -> str:
    mem = get_memory(d.ext_mem)
    ext_start, ext_len = ext_window(ext_bytes)
    code = code_section_bytes(d)
    standalone = d.platform == "standalone"
    lines = [
        f"# {d.name}: design datasheet",
        "",
        f"Generated by ChipLeap{f' for spec {spec_name}' if spec_name else ''}. {d.summary()}.",
    ]
    if workload:
        lines += ["", f"Workload: {workload}."]
    if metrics:
        lines += [
            "",
            "Model prediction: "
            f"{metrics['throughput']:.3g} {unit}/s, {metrics['latency_ms']:.3g} ms per step, "
            f"{metrics['energy_mj']:.3g} mJ/{unit}, {metrics['power_mw']:.3g} mW, "
            f"{metrics['area_mm2']:.3g} mm2 core area.",
        ]
    if metrics and standalone:
        lines += [
            "",
            f"Generated IP: the accelerator with AXI4 interfaces, {metrics['ip_area_mm2']:.3g} "
            "mm2. Everything in the next table is the host system the model assumes around it, "
            "not something ChipLeap generates; the prediction holds for a host like it.",
        ]
    lines += [
        "",
        "## Host system assumed by the model" if standalone else "## System",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Process | {d.tech} |",
        f"| Clock | {_clock(d)} |",
        f"| CPU | {d.cpu} |",
        f"| Bus | {d.bus} |",
        f"| SRAM | {d.banks} x {d.bank_kib} KiB continuous"
        + (f", {d.il_banks} x {d.il_bank_kib} KiB interleaved" if d.il_banks else "")
        + " |",
        f"| External memory | {mem.name + (f' x {d.ext_channels}' if d.ext_channels > 1 else '') if mem else 'none'} |",
    ]
    if not standalone:
        lines.append(f"| Peripherals | always-on, {d.peripherals.summary()} |")
    if standalone:
        lines += [
            "",
            "## Address map",
            "",
            "The IP decodes a 64-byte register window on its AXI4-Lite port, wherever the "
            "host's interconnect places it (the driver's `CHIPLEAP_BASE`). Its AXI4 masters read "
            "X and W and write Y at the addresses software programs, so they must reach the "
            "memory that holds them.",
        ]
    if not standalone:
        lines += [
            "",
            "## Memory map",
            "",
            "| Region | Start | Size |",
            "|---|---|---|",
            f"| Code (SRAM) | 0x00000000 | {code:#x} |",
            f"| Data (SRAM) | {code:#010x} | {d.banks * d.bank_kib * 1024 - code:#x} |",
        ]
        if d.il_banks:
            start = d.banks * d.bank_kib * 1024
            lines.append(
                f"| Interleaved data (SRAM) | {start:#010x} | "
                f"{d.il_banks * d.il_bank_kib * 1024:#x} |"
            )
        lines += [
            "| Debug | 0x10000000 | 0x100000 |",
            "| Base peripherals | 0x20000000 | 0x100000 |",
        ]
        if d.accel:
            lines.append(f"| Accelerator registers | {DEFAULT_REG_BASE:#010x} | 0x40 |")
        lines += [
            "| User peripherals | 0x30000000 | 0x100000 |",
            "| SPI flash | 0x40000000 | 0x1000000 |",
            f"| External slaves (memory) | {ext_start:#010x} | {ext_len:#x} |",
        ]
    if d.accel:
        a = d.accel
        p = rtl_params(a)
        tn = a.rows if a.dataflow == "gemv" else a.cols
        lines += [
            "",
            "## Accelerator",
            "",
            f"{DATAFLOW_NAMES[a.dataflow].capitalize()}: {a.rows} x {a.cols} processing elements "
            f"({a.macs} MACs per cycle), int8 activations, weights up to int{a.w_bits}, int32 "
            f"results. Output tiles are {ACC_ROWS if a.dataflow != 'os' else a.rows} x {tn}.",
            "",
            "| Interface | Width | Purpose |",
            "|---|---|---|",
            *(
                [
                    "| AXI4-Lite slave (`s_axil_*`) | 32 bit | Configuration and status |",
                    f"| AXI4 read masters (`m_axi_ar*`, `m_axi_r*`) | {a.ports} x 32 bit | "
                    "Activations and weights: single-beat INCR reads, ID 0, in order, up to 4 "
                    "in flight per port |",
                    "| AXI4 write master (`m_axi_aw*`, `m_axi_w*`, `m_axi_b*`) | 32 bit | "
                    "Results: single-beat writes |",
                ]
                if standalone
                else [
                    "| Register interface | 32 bit | Configuration and status (PULP reg_intf) |",
                    f"| OBI read masters | {a.ports} x 32 bit | Activations and weights, one "
                    "word per port per cycle |",
                    "| OBI write master | 32 bit | Results |",
                ]
            ),
            "| irq_o | 1 bit | Job done, when IRQ_EN is set |",
            "",
            f"Buffers: {a.abuf_kib} KiB activations and {a.wbuf_kib} KiB weights, "
            + (
                "each split into two slots so the next tile loads while the core computes."
                if a.double_buffer
                else "single slot (loads and compute alternate)."
            ),
            "",
            "RTL parameters: " + ", ".join(arg[2:] for arg in p.verilator_args()) + ".",
            "",
            "### Registers",
            "",
            "| Offset | Name | Access | Description |",
            "|---|---|---|---|",
        ]
        for r in REGISTERS:
            desc = r.desc
            if r.fields:
                desc += " " + " ".join(f"[{b}] {n}: {t}" for b, n, t in r.fields)
            lines.append(f"| {r.offset:#04x} | {r.name} | {r.access} | {desc} |")
        lines += [
            "",
            "### Programming",
            "",
            "1. Call `chipleap_plan(M, K, N, fmt, &plan)` from `sw/chipleap_driver.h`. It picks",
            "   the tile sizes the explorer's model assumed and returns the padded K.",
            "2. Lay out X as M rows of `plan.k_pad` bytes and W as N rows of `plan.k_pad` packed",
            "   weights, zero-padded.",
            "3. Call `chipleap_start(...)`, then poll `chipleap_busy()` or wait for the interrupt.",
            "4. `chipleap_cycles()` returns the cycle count, which the model predicts exactly in",
            "   simulation without memory stalls.",
            "",
        ]
        if standalone:
            lines += [
                "### Integration with any host",
                "",
                "Instantiate `chipleap_accel_axi_top` from `rtl/`. Connect `s_axil_*` to a",
                "peripheral port of the host's interconnect and define `CHIPLEAP_BASE` to that",
                "address before including the driver. Read port 0 with the write channels is one",
                "full AXI4 master; further read ports are read-only masters. Give them a path to",
                "the memory that holds the weights (on a Zynq, an HP or ACP port; on an Arm or",
                "RISC-V SoC, a manager port of the main interconnect), and route `irq_o` to an",
                "interrupt input. `AXI_ID_WIDTH` in the top file sets the ID width. The model",
                "assumes each port can move one 32-bit word per cycle, which needs the",
                "interconnect to accept back-to-back single-beat reads.",
            ]
        else:
            lines += [
                "### Integration into X-HEEP",
                "",
                "Instantiate `chipleap_accel_xheep` in your top level next to `core_v_mini_mcu`:",
                "connect `reg_req_i`/`reg_rsp_o` to a slot of the external peripheral bus (the",
                f"driver assumes base {DEFAULT_REG_BASE:#010x}), the read and write OBI masters",
                "to `ext_xbar_master_req_i`/`ext_xbar_master_resp_o`, and `irq_o` to a free fast",
                "interrupt. Generate the MCU with `make mcu-gen X_HEEP_CFG=xheep/<design>.py`.",
            ]
    return "\n".join(lines) + "\n"
