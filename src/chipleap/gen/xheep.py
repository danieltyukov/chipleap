def code_section_bytes(d: Design) -> int:
    """Size of the code section: X-HEEP's default, or half the continuous RAM if smaller."""
    cont = d.banks * d.bank_kib * 1024
    return min(DEFAULT_CODE_BYTES, (cont // 2) // 0x800 * 0x800)


def ext_window(ext_bytes: float) -> tuple[int, int]:
    return EXT_LARGE if ext_bytes > EXT_DEFAULT[1] else EXT_DEFAULT


