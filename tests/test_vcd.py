"""Counterexample traces from VCD: one value per step for the top scope's signals."""

from chipleap.rtl.vcd import read_trace

# The shape yosys-smtbmc writes: a step counter at the root, the clock toggling between
# steps, a witness scope inside the top module, and names that are not identifiers.
SMTBMC = """\
$version Generated by Yosys-SMTBMC $end
$timescale 1ns $end
$var integer 32 t smt_step $end
$var event 1 ! smt_clock $end
$scope module fifo $end
$scope module _witness_ $end
$var wire 1 n0 anyinit_procdff_102 $end
$upscope $end
$var wire 1 n13 clk_i $end
$var wire 3 n14 count $end
$var wire 1 n20 full_o $end
$var wire 8 n28 mem<0> $end
$var wire 2 n29 $auto$opt.cc:12 $end
$upscope $end
$enddefinitions $end
#0
1!
b00000000000000000000000000000000 t
b1 n13
b0 n0
b000 n14
b0 n20
bxxxxxxxx n28
b00 n29
#5
b0 n13
#10
1!
b00000000000000000000000000000001 t
b1 n13
b001 n14
b00010010 n28
#15
b0 n13
#20
1!
b00000000000000000000000000000010 t
b1 n13
b100 n14
b1 n20
"""

# EQY's sat strategy: no step counter, one timestamp per step, escaped names.
EQY = """\
$timescale 1ns $end
$scope module \\miter $end
$var wire 1 v7 \\__pi_clk_i $end
$var wire 6 v14 \\__po_q_o__gate $end
$var wire 6 v15 \\__po_q_o__gold $end
$upscope $end
$enddefinitions $end
#0
b0 v7
b000000 v14
b000000 v15
#1
b1 v7
b000011 v14
b000001 v15
"""


def test_smtbmc_trace_has_one_value_per_step():
    t = read_trace(SMTBMC)
    assert t["steps"] == 3
    # The clock is sampled at each step, not at its half-period toggles.
    assert t["signals"] == {
        "clk_i": [1, 1, 1],
        "count": [0, 1, 4],
        "full_o": [0, 0, 1],
        "mem<0>": ["xxxxxxxx", 18, 18],
    }
    assert "truncated" not in t


def test_eqy_trace_uses_timestamps_and_unescapes_names():
    t = read_trace(EQY, keep=lambda n: n.startswith("__po_"))
    assert t == {"steps": 2, "signals": {"__po_q_o__gate": [0, 3], "__po_q_o__gold": [0, 1]}}


def test_large_traces_are_cut_and_say_so():
    t = read_trace(SMTBMC, max_signals=2, max_steps=2)
    assert t["steps"] == 3 and t["truncated"] is True
    assert list(t["signals"]) == ["clk_i", "count"] and t["signals"]["count"] == [0, 1]


def test_an_empty_or_broken_file_is_an_empty_trace():
    assert read_trace("") == {"steps": 0, "signals": {}}
    assert read_trace("$enddefinitions $end\n#0\nb1 nope\n")["signals"] == {}
